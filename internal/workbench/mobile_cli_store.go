type mobileRun struct {
	record       *mobileRecord
	cancel       context.CancelFunc
	done         chan struct{}
	approvalGate chan struct{}
	pending      *mobileDecision
}
type mobileCLIStore struct {
	mu         sync.Mutex
	active     map[string]*mobileRun
	catalog    map[string]mobileSummary
	running    map[string]bool // Fresh guest process observation, never restored from disk.
	generation string
}

func (m *mobileCLIStore) epochLocked() string {
	if m.generation == "" {
		m.generation = uuid.NewString()
	}
	return m.generation
}

func mobileID(id string) bool {
	v, err := uuid.Parse(id)
	return err == nil && v.Version() == 4 && v.Variant() == uuid.RFC4122 && v.String() == id
}
func validCLIUUID(id string) bool {
	v, err := uuid.Parse(id)
	return err == nil && v.String() == id
}
func mobileRecordPath(profile, id string) string {
	return filepath.Join(profile, "mobile-cli-sessions", id+".json")
}
func (record *mobileRecord) changed() {
	record.Revision++
	record.UpdatedAt = time.Now().UTC()
}
func (record *mobileRecord) summary() mobileSummary {
	view := record.mobileSummary
	view.AccountID = record.Account.ID
	return view
}
func (record *mobileRecord) snapshot() mobileSession {
	view := record.mobileSession
	view.AccountID = record.Account.ID
	if sw := record.Switch; sw != nil {
		view.AccountSwitch = &claudeSwitchView{ID: sw.ID, Phase: sw.Phase, TargetLabel: sw.TargetLabel, Error: sw.Error}
	}
	if !record.Terminal {
		view.Active = record.turnActive()
	}
	view.mediaWorkingDir = record.GuestWorkspace
	view.TerminalAvailable = record.Terminal
	view.DesktopTerminalID = record.TerminalID
	if record.CustomTitle != "" {
		view.Title = record.CustomTitle
	}
	view.Turns = append([]mobileTurn{}, record.Turns...)
	return view
}

func (record *mobileRecord) turnActive() bool {
	if len(record.Turns) == 0 {
		return false
	}
	status := record.Turns[len(record.Turns)-1].Status
	return status == "running" || status == "stopping" || status == "queued"
}

// Caller holds the store lock. The durable running marker prevents a restarted
// service from silently executing a previously accepted request twice.
func (m *mobileCLIStore) record(profile, id string) (*mobileRecord, error) {
	if !mobileID(id) {
		return nil, os.ErrNotExist
	}
	if run := m.active[id]; run != nil {
		if run.cancel == nil && writePrivate(mobileRecordPath(profile, id), run.record) == nil {
			delete(m.active, id)
		}
		return run.record, nil
	}
	path := mobileRecordPath(profile, id)
	if err := host.CheckPrivateFile(path); err != nil {
		return nil, err
	}
	info, err := os.Stat(path)
	if err != nil {
		return nil, err
	}
	if info.Size() > 4<<20 {
		return nil, errors.New("CLI 会话记录过大")
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var record mobileRecord
	if json.Unmarshal(b, &record) != nil || record.ID != id || !validCLIUUID(record.CLIID) || record.Workspace == "" || record.Turns == nil {
		return nil, errors.New("CLI 会话记录无效，请从备份恢复")
	}
	// Older "delete" actions only hid the row and kept the CLI transcript.
	if record.Deleted && !record.Purged {
		record.Deleted, record.Archived = false, true
		if err := writePrivate(path, &record); err != nil {
			return nil, err
		}
	}
	record.Generation = m.epochLocked()
	if n := len(record.Turns); n > 0 && !record.Terminal {
		turn := &record.Turns[n-1]
		if turn.Status == "running" || turn.Status == "stopping" {
			turn.Status, turn.Error = "interrupted", "主机服务重新启动。请检查本轮结果后再发送消息。"
			record.changed()
			if err := writePrivate(path, &record); err != nil {
				return nil, err
			}
		}
	}
	return &record, nil
}
func (m *mobileCLIStore) summaries(profile string, granted map[string]bool, archived bool) ([]mobileSummary, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	list := []mobileSummary{}
	if m.catalog == nil {
		entries, err := os.ReadDir(filepath.Join(profile, "mobile-cli-sessions"))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		catalog := make(map[string]mobileSummary, len(entries))
		for _, entry := range entries {
			id, ok := strings.CutSuffix(entry.Name(), ".json")
			if !ok || !mobileID(id) {
				continue
			}
			record, err := m.record(profile, id)
			if err != nil {
				return nil, err
			}
			catalog[id] = record.summary()
		}
		m.catalog = catalog
	}
	for id, summary := range m.catalog {
		if run := m.active[id]; run != nil {
			summary = run.record.summary()
			summary.Active = run.record.turnActive()
		}
		summary.Running = m.running[id]
		if granted[summary.Workspace] && !summary.Deleted && summary.Archived == archived {
			if summary.CustomTitle != "" {
				summary.Title = summary.CustomTitle
			}
			list = append(list, summary)
		}
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].Pinned != list[j].Pinned {
			return list[i].Pinned
		}
		return list[i].UpdatedAt.After(list[j].UpdatedAt)
	})
	return list, nil
}
func (m *mobileCLIStore) create(profile, workspace, id string) (mobileSession, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	record, err := m.record(profile, id)
	if err == nil {
		if record.Deleted || record.Archived {
			return mobileSession{}, errors.New("此会话已归档或删除，请从已归档会话恢复或新建会话")
		}
		if record.Workspace != workspace {
			return mobileSession{}, errors.New("创建请求已用于其他项目")
		}
		return record.snapshot(), nil
	}
	if !errors.Is(err, os.ErrNotExist) {
		return mobileSession{}, err
	}
	record = &mobileRecord{mobileSession: mobileSession{mobileSummary: mobileSummary{ID: id, Workspace: workspace, Title: "新会话"}, Turns: []mobileTurn{}}, CLIID: uuid.NewString()}
	record.Generation = m.epochLocked()
	record.changed()
	err = writePrivate(mobileRecordPath(profile, id), record)
	if err == nil && m.catalog != nil {
		m.catalog[id] = record.summary()
	}
	return record.snapshot(), err
}
func mobileTrim(text string, limit int) string {
	if len(text) <= limit {
		return text
	}
	for limit > 0 && !utf8.RuneStart(text[limit]) {
		limit--
	}
	return text[:limit]
}
func (m *mobileCLIStore) activeAccounts() map[string]int {
	m.mu.Lock()
	defer m.mu.Unlock()
	count := map[string]int{}
	for _, run := range m.active {
		if run.cancel != nil {
			count[run.record.Account.ID]++
		}
	}
	return count
}
func (m *mobileCLIStore) stopAll() {
	m.mu.Lock()
	done := make([]chan struct{}, 0, len(m.active))
	for _, run := range m.active {
		if run.cancel != nil {
			run.cancel()
			done = append(done, run.done)
		}
	}
	m.mu.Unlock()
	for _, ch := range done {
		<-ch
	}
}
