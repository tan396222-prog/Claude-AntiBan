import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createRequire } from "node:module";

const run = promisify(execFile);
const target = process.argv[2];
assert.ok(path.isAbsolute(target || ""), "supply an absolute Cage.app or full Cage helper path");
const packaged = target.endsWith(".app");
const cage = packaged ? path.join(target, "Contents/Resources/cage") : target;
const evidence = process.env.CAGE_REMOTE_QA_DIR;
if (evidence) await fs.mkdir(evidence, { recursive: true });
const profile = await fs.mkdtemp(path.join(os.tmpdir(), "cage-packaged-"));
const env = { ...process.env, CLAUDE_CAGE_CONFIG: path.join(profile, "config.json") };
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CAGE_PLAYWRIGHT_MODULE || "playwright");
let browser;
try {
  const { stdout } = await run(cage, ["desktop", "--json"], { env });
  const entry = JSON.parse(stdout);
  assert.equal(entry.status, "ready");
  assert.equal(entry.controller.version, (await fs.readFile(new URL("../../VERSION", import.meta.url), "utf8")).trim());
  browser = await chromium.launch({ headless: true, executablePath: process.env.CAGE_TEST_BROWSER_PATH });
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const statusResponse = page.waitForResponse((response) => response.url().endsWith("/api/status") && response.ok());
  await page.goto(entry.url);
  await page.getByLabel("用户名",{exact:true}).waitFor();
  const initial = await page.evaluate(async () => (await fetch("/api/client/local-status")).json());
  assert.ok(initial.known && initial.service_running && !initial.running, "opening the local home must not boot the VM");
  assert.equal(await page.getByRole("heading",{name:"选择工作环境"}).count(),0);
  if (evidence) await page.screenshot({ path:path.join(evidence,"desktop-first-open.png") });
  const password = randomBytes(24).toString("base64url");
  await page.getByLabel("用户名",{exact:true}).fill("Packaged Smoke");
  await page.getByLabel("设置密码",{exact:true}).fill(password);
  await page.getByLabel("确认密码",{exact:true}).fill(password);
  await page.getByRole("button",{name:"创建本地账户",exact:true}).click();
  const status = await (await statusResponse).json();
  assert.equal(status.vm_running, false);
  await page.getByRole("button", { name: "配置网络与代理", exact: true }).waitFor();
  const nav = page.getByRole("navigation", {name:"主导航"});
  assert.equal(await nav.getByRole("button", {name:/Claude(?: Code)? 会话/}).count(), 0);
  assert.equal(await nav.getByRole("button", {name:"Claude Desktop",exact:true}).count(), 1);
  await page.getByRole("button",{name:"SSH 主机",exact:true}).click();
  await page.getByRole("complementary",{name:"SSH 主机"}).waitFor();
  if (evidence) await page.screenshot({ path:path.join(evidence,"local-ssh-sidebar.png") });
  await page.getByRole("button",{name:"返回工作台侧栏"}).click();
  assert.equal(new URL(page.url()).hash, "", "launch ticket was not removed");
  await page.getByRole("button", { name: "配置网络与代理", exact: true }).click();
  await page.getByText("添加来源", { exact: true }).first().waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ checks: ["original local home by default", "VM stopped throughout", "isolated local account setup", packaged ? "packaged helper bootstrap" : "development helper bootstrap", "real session and APIs", "embedded production UI loaded", "private profile onboarding", "launch ticket removed"], version: entry.controller.version }));
} finally {
  await browser?.close();
  await run(cage, ["prepare-update", "--json"], { env });
  await fs.rm(profile, { recursive: true, force: true });
  await fs.rm(profile + "-workspace", { recursive: true, force: true });
}
