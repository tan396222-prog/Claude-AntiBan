import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { createWorkbench } from "./workbench-fixture.mjs";

// Isolated UI data; no running environment, credentials or personal files.
const { browser, page, state, errors } = await createWorkbench();
page.setDefaultTimeout(10000);
const output = process.env.CAGE_MENU_CAPTURE || `/tmp/cage-browser-menu-${browser.browserType().name()}`;
await fs.mkdir(output, { recursive: true });
await page.route("**/api/vault/browser", route => route.fulfill({ json: {
  available: true, entries: [], candidates: [], origin: "https://example.test",
} }));
try {
  state.status.ready = state.status.vm_running = true;
  state.tabs = [{ id: "menu-web", kind: "web", title: "测试网页", url: "https://example.test" }];
  state.active = "menu-web";
  await page.reload();
  await page.getByRole("button", { name: "打开浏览器", exact: true }).click();
  await page.getByRole("button", { name: "收起侧栏", exact: true }).click();
  const trigger = page.getByRole("button", { name: "浏览器菜单", exact: true });
  const menu = page.getByRole("menu", { name: "浏览器菜单", exact: true });
  const header = page.locator(".browser-chrome");
  const star = header.getByRole("button", { name: "收藏此页", exact: true });
  const folder = header.getByRole("button", { name: "收藏夹", exact: true });
  for (const width of [1280, 375]) {
    await page.setViewportSize({ width, height: 850 });
    const address = await page.locator(".address-bar").boundingBox();
    const starBox = await star.boundingBox(), folderBox = await folder.boundingBox(), triggerBox = await trigger.boundingBox();
    assert.ok(address.x + address.width <= starBox.x && starBox.x + starBox.width <= folderBox.x && folderBox.x + folderBox.width <= triggerBox.x, "favorites stay beside the address bar without overlapping");
    assert.ok(triggerBox.x + triggerBox.width <= width, "toolbar actions stay within the viewport");
    await page.screenshot({ path: `${output}/toolbar-${width}.png` });
    const closed = await header.boundingBox();
    await trigger.focus();
    await trigger.press("ArrowDown");
    await menu.waitFor();
    const opened = await header.boundingBox(), box = await menu.boundingBox();
    assert.ok(Math.abs(opened.height - closed.height) < 1, "menu does not change the header height");
    const body = await page.locator(".browser-lane .pane-body").boundingBox();
    assert.ok(box.y >= body.y - 1 && box.y < body.y + 10, "menu overlays the browser content below the toolbar");
    assert.ok(box.width <= 240 && box.x >= 0 && box.x + box.width <= width, "menu stays compact and within the viewport");
    const items = menu.getByRole("menuitem");
    const required = ["下载", "密码"];
    assert.deepEqual((await items.allTextContents()).filter(text => required.includes(text)), required);
    assert.equal(await menu.getByRole("menuitem", { name: /收藏/ }).count(), 0);
    for (let i = 1; i < await items.count(); i++) assert.ok((await items.nth(i).boundingBox()).y > (await items.nth(i - 1).boundingBox()).y);
    assert.equal(await items.first().evaluate(el => el === document.activeElement), true);
    await page.keyboard.press("ArrowDown");
    assert.equal(await items.nth(1).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press("End");
    assert.equal(await menu.getByRole("menuitem", { name: "设置", exact: true }).evaluate(el => el === document.activeElement), true);
    await menu.getByRole("menuitem", { name: "密码", exact: true }).focus();
    await page.keyboard.press("Enter");
    const picker = page.getByRole("region", { name: "当前网站的密码" });
    await picker.waitFor();
    await picker.getByText("此网站尚未保存账号密码。", { exact: true }).waitFor();
    await page.keyboard.press("Escape");
    await picker.waitFor({ state: "hidden" });
    await page.screenshot({ path: `${output}/menu-${width}.png` });
    await page.keyboard.press("Escape");
    await menu.waitFor({ state: "hidden" });
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
    assert.ok(Math.abs((await header.boundingBox()).height - closed.height) < 1, "closing restores the original layout");
    await trigger.click();
    await page.getByRole("textbox", { name: "网页地址或搜索" }).click();
    await menu.waitFor({ state: "hidden" });
  }
  await star.click();
  const editor = page.getByRole("dialog", { name: "添加收藏", exact: true });
  await editor.waitFor();
  await menu.waitFor({ state: "hidden" });
  await editor.getByRole("button", { name: "取消", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  assert.equal(await star.evaluate(el => el === document.activeElement), true);
  await folder.focus();
  await folder.press("Enter");
  const favorites = page.getByRole("dialog", { name: "收藏夹", exact: true });
  await favorites.waitFor();
  await menu.waitFor({ state: "hidden" });
  await favorites.getByRole("button", { name: "关闭收藏夹", exact: true }).click();
  assert.equal(await folder.evaluate(el => el === document.activeElement), true);
  await trigger.click();
  await menu.getByRole("menuitem", { name: "浏览器下载", exact: true }).click();
  const downloads = page.getByRole("dialog", { name: "下载文件", exact: true });
  await downloads.waitFor();
  await menu.waitFor({ state: "hidden" });
  await downloads.getByRole("button", { name: "关闭面板", exact: true }).click();
  await downloads.waitFor({ state: "hidden" });
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  await page.keyboard.press("Meta+d");
  await editor.waitFor();
  await editor.getByRole("button", { name: "取消", exact: true }).click();
  await page.keyboard.press("Meta+Shift+o");
  await favorites.waitFor();
  await page.keyboard.press("Escape");
  await favorites.waitFor({ state: "hidden" });
  assert.equal(await folder.evaluate(el => el === document.activeElement), true);
  assert.deepEqual(errors, []);
  console.log(`PASS: favorites toolbar at 1280/375, direct and keyboard access, focus restoration, browser menu, downloads, passwords and favorites shortcuts. Screenshots: ${output}`);
} finally { await browser.close(); }
