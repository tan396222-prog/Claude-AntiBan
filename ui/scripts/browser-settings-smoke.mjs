import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { smokeCaptureDirectory } from './smoke-captures.mjs';
import { createSettingsWorkbench } from './browser-settings-fixture.mjs';
const engine = process.env.CAGE_TEST_BROWSER || 'chromium';
const output = await smokeCaptureDirectory('browser-settings-' + engine);
const f = await createSettingsWorkbench();
const { page, controller, fixtureState, errors } = f;
page.setDefaultTimeout(12000);
const checks = [];
const shot = name => page.screenshot({ path: join(output, name + '.png'), animations: 'disabled' });
try {
  await page.getByRole('button', { name: '打开浏览器', exact: true }).click();
  await page.getByRole('button', { name: '浏览器菜单', exact: true }).click();
  await page.getByRole('menuitem', { name: '设置', exact: true }).click();
  const settings = page.getByRole('region', { name: '浏览器设置', exact: true });
  const nav = settings.getByRole('navigation', { name: '浏览器设置分类' });
  await settings.waitFor();
  const address = settings.getByRole('textbox', { name: '新标签页地址', exact: true });
  const nextHome = controller.origin + '/custom';
  await address.fill(nextHome);
  await nav.getByRole('button', { name: '外观', exact: true }).click();
  await nav.getByRole('button', { name: '新标签页', exact: true }).click();
  assert.equal(await address.inputValue(), nextHome, 'switching categories preserves unsaved address');
  fixtureState.failSave = true;
  await settings.getByRole('button', { name: '保存地址', exact: true }).click();
  await settings.getByRole('alert').getByText('保存浏览器设置失败，请重试', { exact: true }).waitFor();
  assert.equal(await address.inputValue(), nextHome);
  fixtureState.failSave = false;
  await settings.getByRole('button', { name: '保存地址', exact: true }).click();
  await settings.getByRole('status').getByText('已保存', { exact: true }).waitFor();
  await shot('new-tab-settings');
  await page.getByRole('button', { name: '新建网页', exact: true }).click();
  await controller.waitFor(async () => (await controller.api('/tabs')).tabs.some(tab => tab.url === nextHome), 'new page uses saved address');
  await page.waitForFunction(url => document.querySelector('.address-bar input')?.value === url, nextHome);
  await page.getByRole('button', { name: '浏览器菜单', exact: true }).click();
  await page.getByRole('menuitem', { name: '设置', exact: true }).click();
  await settings.waitFor();
  assert.equal(await page.getByRole('tab', { name: '设置', exact: true }).count(), 1);
  await nav.getByRole('button', { name: '外观', exact: true }).click();
  const layout = settings.getByRole('combobox', { name: '标签栏布局', exact: true });
  await layout.click();
  await settings.getByRole('option', { name: '竖排（左侧）', exact: true }).click();
  await page.getByRole('complementary', { name: '竖排标签栏' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: '打开浏览器', exact: true }).click();
  await page.getByRole('complementary', { name: '竖排标签栏' }).waitFor();
  await settings.waitFor();
  await nav.getByRole('button', { name: '新标签页', exact: true }).click();
  assert.equal(await address.inputValue(), nextHome);
  checks.push('real menu opens and reuses settings tab; unsaved form survives category changes; save failure retains input; saved default affects new tabs; address and layout survive reload');

  await page.getByRole('button', { name: /^设置/ }).filter({ has: page.locator('svg') }).first().click();
  const globalSettings = page.getByRole('region', { name: '设置', exact: true });
  await globalSettings.waitFor();
  assert.equal(await globalSettings.getByRole('button', { name: '浏览器', exact: true }).count(), 0);
  assert.equal(await globalSettings.getByText('浏览器默认网站', { exact: true }).count(), 0);
  await globalSettings.getByRole('button', { name: '返回工作台', exact: true }).first().click();
  await nav.getByRole('button', { name: '扩展', exact: true }).click();
  await settings.getByText('让浏览器更合用', { exact: true }).waitFor();
  await settings.getByRole('button', { name: '从本机导入', exact: true }).click();
  const importer = settings.getByRole('region', { name: '从本机导入扩展', exact: true });
  await importer.getByText('阅读助手', { exact: true }).waitFor();
  assert.equal(await importer.getByRole('checkbox').nth(1).isDisabled(), true);
  await importer.getByRole('button', { name: '选择全部兼容扩展', exact: true }).click();
  await importer.getByRole('button', { name: '导入所选扩展（1）', exact: true }).click();
  await importer.getByText('已导入，保持停用', { exact: true }).waitFor();
  await shot('import-results');
  await importer.getByRole('button', { name: '完成并关闭', exact: true }).click();
  await importer.waitFor({ state: 'hidden' });
  const enabled = settings.getByRole('checkbox', { name: '启用 阅读助手', exact: true });
  assert.equal(await enabled.isChecked(), false);
  await enabled.click();
  await page.waitForFunction(() => document.querySelector('input[aria-label="启用 阅读助手"]')?.checked === true);
  await controller.waitFor(async () => (await controller.api('/extensions', { mode: 'list' })).items.some(item => item.enabled), 'enable imported extension');
  await settings.evaluate(element => { element.scrollTop = 0; });
  await shot('extensions-imported');
  const web = await controller.api('/new', { url: controller.origin + '/import-test' });
  await controller.waitFor(() => controller.evaluate(web.id, 'document.documentElement.dataset.cageSettingsExtension === "active"'), 'imported extension runs');
  await page.getByRole('tab', { name: '设置', exact: true }).click();
  await settings.getByRole('button', { name: '刷新扩展', exact: true }).click();
  await settings.getByRole('button', { name: '移除', exact: true }).click();
  await page.getByRole('dialog', { name: '移除此扩展？', exact: true }).getByRole('button', { name: '移除扩展', exact: true }).click();
  await settings.getByText('让浏览器更合用', { exact: true }).waitFor();
  checks.push('global settings no longer own browser preferences; local import shows per-extension compatibility and permissions, skips legacy extensions, preserves disabled state; enable runs real content script and removal works');

  const file = settings.getByLabel('选择扩展 ZIP', { exact: true });
  await file.setInputFiles({ name: 'reading-extension.zip', mimeType: 'application/zip', buffer: f.archive });
  const preview = settings.getByRole('region', { name: '确认扩展安装', exact: true });
  await preview.getByText('storage', { exact: true }).waitFor();
  await preview.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal((await controller.api('/extensions', { mode: 'list' })).items.length, 0);
  await file.setInputFiles({ name: 'reading-extension.zip', mimeType: 'application/zip', buffer: f.archive });
  await preview.getByRole('button', { name: '安装扩展', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('input[aria-label="启用 阅读助手"]')?.checked === true);
  checks.push('ZIP install shows permissions before confirmation; cancel installs nothing; confirming installs the real extension');
  await settings.getByRole('textbox', { name: '搜索浏览器设置', exact: true }).fill('新标签');
  await address.waitFor();
  await settings.getByRole('textbox', { name: '搜索浏览器设置', exact: true }).fill('');
  await nav.getByRole('button', { name: '外观', exact: true }).click();
  await page.setViewportSize({ width: 820, height: 558 });
  await shot('minimum-window');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.setViewportSize({ width: 1280, height: 850 });
  await page.evaluate(() => { document.documentElement.style.zoom = '2'; });
  await settings.getByRole('combobox', { name: '浏览器设置分类', exact: true }).waitFor();
  await settings.getByRole('combobox', { name: '标签栏布局', exact: true }).scrollIntoViewIfNeeded();
  await shot('zoom-200');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.evaluate(() => { document.documentElement.style.zoom = ''; });
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'result.json'), JSON.stringify({ passed: true, engine, checks }, null, 2) + '\n');
  console.log(JSON.stringify({ passed: true, engine, checks }, null, 2));
} catch (error) { await shot('failure'); throw error; }
finally { await f.close(); }
